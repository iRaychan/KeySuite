const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');const path=require('node:path');
const root=path.resolve(__dirname,'..');const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const release=JSON.parse(read('RELEASE.json')),html=read('index.html');
assert.equal(release.version,'5.00.70');assert.equal(release.production_deployed,false);
assert.match(html,/src="release-version\.js\?v=50070"/);
for(const f of ['g-data-v50068.js','g-pdf-v50068.js','g-series-v50068.js'])assert.match(html,new RegExp(`src="${f.replaceAll('.','\\.')}\\?v=50070"`));
assert.doesNotMatch(html,/src="g-(?:data|pdf|series)-v50069\.js/);
const nav=html.match(/<div class="v391-bgreich-list">([\s\S]*?)<\/div>/)[1];
const labels=[...nav.matchAll(/<button[^>]*>([^<]+)<\/button>/g)].map(x=>x[1]);
assert.deepEqual(labels,['BFI','BGF','BSV','BSW','CHC C4','CHC C6','CR','ES','G','ISO','KV','Motor']);
assert.equal((nav.match(/data-page="productG"/g)||[]).length,1);
for(const id of ['gProductRows','gSelectorRows'])assert.match(html,new RegExp(`<th>Cost</th><th>Curve</th><th>Quote</th>[^<]*</tr></thead><tbody id="${id}"`));
assert.match(read('v50051-version-lock.js'),/const V=window\.KEYSUITE_VERSION/);
assert.doesNotMatch(read('v50051-version-lock.js'),/const V='5\.00\.67'/);
assert.match(read('v41200-bootstrap.js'),/const VERSION=window\.KEYSUITE_VERSION/);
const context={window:{},document:{},console};vm.createContext(context);vm.runInContext(read('g-data-v50068.js'),context);
const models=context.window.KeySuiteGData.models;assert.equal(models.length,12);
assert.deepEqual(Array.from(models.filter(m=>m.curve?.length),m=>m.model),['G32-10-2M','G32-10-2T']);
const code=read('g-series-v50068.js');assert.match(code,/motor_phase:p\.phase/);
assert.match(code,/data-g-cost/);assert.match(code,/p\.curve\?\.length\?'<button type="button" class="btn secondary product-action-button" data-g-curve>/);
assert.match(code,/class="g-action-cell"><button type="button" class="btn action-quote product-action-button" data-g-quote/);
const scriptRefs=[...html.matchAll(/<script[^>]*src="([^"?]+)(?:\?[^" ]*)?"/g)].map(x=>x[1]).filter(x=>!x.startsWith('http'));
assert.deepEqual(scriptRefs.filter(f=>!fs.existsSync(path.join(root,f))),[]);
console.log(`PASS: release version, 12 G variants, 2 curve variants, fixed action columns, navigation and ${scriptRefs.length} script paths`);
