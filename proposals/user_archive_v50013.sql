-- KeySuite V5.00.13 review proposal. Do not apply to production without approval.
-- Preserves ks_user_access and all business/audit rows. Supabase Auth sessions are
-- revoked by an Edge Function through the service-role-only helper below.

alter table public.ks_user_access
  add column if not exists archived_at timestamptz,
  add column if not exists archived_by_email text;

create table if not exists public.ks_user_archive_audit_v50013 (
  id bigint generated by default as identity primary key,
  company_id text not null,
  target_email text not null,
  target_display_name text,
  action text not null check (action in ('archive','restore')),
  changed_by_email text not null,
  changed_at timestamptz not null default now()
);

alter table public.ks_user_archive_audit_v50013 enable row level security;
revoke all on table public.ks_user_archive_audit_v50013 from public, anon, authenticated;
grant select, insert on table public.ks_user_archive_audit_v50013 to service_role;
grant usage, select on sequence public.ks_user_archive_audit_v50013_id_seq to service_role;

create or replace function public.keysuite_revoke_user_sessions_v50013(
  p_email text,
  p_revoke boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
  v_deleted integer := 0;
begin
  select id into v_user_id
  from auth.users
  where lower(email)=lower(trim(p_email))
  limit 1;

  if v_user_id is not null and p_revoke then
    delete from auth.sessions where user_id=v_user_id;
    get diagnostics v_deleted = row_count;
  end if;

  return jsonb_build_object('user_id',v_user_id,'sessions_revoked',v_deleted);
end;
$$;

revoke all on function public.keysuite_revoke_user_sessions_v50013(text,boolean) from public, anon, authenticated;
grant execute on function public.keysuite_revoke_user_sessions_v50013(text,boolean) to service_role;

comment on function public.keysuite_revoke_user_sessions_v50013(text,boolean)
is 'V5.00.13 service-role-only helper used by keysuite-manage-user-status. Never grant to browser roles.';

create or replace function public.keysuite_set_user_archive_v50013(
  p_email text,
  p_action text,
  p_changed_by text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(trim(coalesce(p_email,'')));
  v_changed_by text := lower(trim(coalesce(p_changed_by,'')));
  v_action text := lower(trim(coalesce(p_action,'')));
  v_company text;
  v_display_name text;
begin
  if v_action not in ('archive','restore') then raise exception 'Action must be archive or restore.'; end if;
  if v_email=v_changed_by then raise exception 'The Owner cannot archive their own account.'; end if;

  select company_id into v_company
  from public.ks_user_access
  where lower(email)=v_changed_by and lower(coalesce(role,''))='owner' and active=true
  limit 1;
  if v_company is null then raise exception 'Only an active Owner can archive or restore users.'; end if;

  select display_name into v_display_name
  from public.ks_user_access
  where lower(email)=v_email and company_id=v_company
  limit 1;
  if not found then raise exception 'The selected user was not found in the Owner company.'; end if;

  update public.ks_user_access
  set active=(v_action='restore'),
      archived_at=case when v_action='archive' then now() else null end,
      archived_by_email=case when v_action='archive' then v_changed_by else null end
  where lower(email)=v_email and company_id=v_company;

  insert into public.ks_user_archive_audit_v50013(
    company_id,target_email,target_display_name,action,changed_by_email,changed_at
  ) values (v_company,v_email,v_display_name,v_action,v_changed_by,now());

  return jsonb_build_object('email',v_email,'action',v_action,'company_id',v_company);
end;
$$;

revoke all on function public.keysuite_set_user_archive_v50013(text,text,text) from public, anon, authenticated;
grant execute on function public.keysuite_set_user_archive_v50013(text,text,text) to service_role;

comment on function public.keysuite_set_user_archive_v50013(text,text,text)
is 'V5.00.13 service-role-only archive/restore transaction with independent active-Owner validation and audit persistence.';
